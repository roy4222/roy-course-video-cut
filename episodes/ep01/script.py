S=[]
def L(sc,text,say=None,gap=0.0): S.append(dict(sc=sc,text=text,say=say,gap=gap))
sc='title'
L(sc,'嗨，歡迎來到機器學習補習班。這是第一集：序章。')
L(sc,'這一集我們完全從零開始，不用會數學，也不用會寫程式。')
L(sc,'看完之後，你會知道機器學習到底在做什麼，以及後面一直會出現的幾個基本名詞。')
sc='hook'
L(sc,'先從一個你每天都會用到的東西開始：電子郵件信箱。')
L(sc,'每天都有信寄進來，有些是老師的通知，有些是莫名其妙的廣告。')
L(sc,'奇怪的是，那些廣告信，常常自己就跑進「垃圾郵件」資料夾了。')
L(sc,'信箱是怎麼知道，哪一封是垃圾信的？')
L(sc,'答案就是今天的主角：機器學習。')
sc='rules'
L(sc,'我們先想想，如果不用機器學習，要怎麼做？')
L(sc,'最直覺的方法，是請工程師自己寫規則。')
L(sc,'例如：信裡只要出現「免費」兩個字，就丟進垃圾郵件。')
L(sc,'聽起來不錯，但問題馬上就來了。')
L(sc,'學校寄來的「免費講座通知」，也被丟掉了。')
L(sc,'而廣告商只要把「免費」寫成「兔費」，就輕鬆躲過規則。')
L(sc,'規則越寫越多，卻永遠追不上變化。')
sc='paradigm'
L(sc,'這就是「傳統寫程式」的做法：人先寫好規則，電腦照著規則，把資料變成答案。')
L(sc,'機器學習，把這個方向反過來。')
L(sc,'我們給電腦大量的資料，再加上每一筆資料的正確答案。')
L(sc,'例如一萬封信，每一封都標好「是垃圾信」或「不是垃圾信」。')
L(sc,'然後，讓電腦自己去找出規則。')
L(sc,'電腦找出來的這套規則，我們叫它「模型」。')
L(sc,'有了模型，新的信一寄進來，就能自動判斷。')
sc='define'
L(sc,'所以用一句話來說：機器學習，就是讓電腦從過去的例子裡，自己學出規則。')
L(sc,'這跟人學東西很像。')
L(sc,'小朋友不是先背「貓有尖耳朵、有鬍鬚」這種定義，才認得貓的。')
L(sc,'而是看過很多隻貓以後，下次看到一隻沒見過的貓，也認得出來。')
L(sc,'課堂講義也是這樣說的：機器學習的演算法，是從經驗中學習。')
L(sc,'這裡的「經驗」，指的就是資料。')
sc='house'
L(sc,'既然機器學習是從資料學習，我們就要先看懂，資料長什麼樣子。')
L(sc,'換個例子：假設你想知道一間房子大概值多少錢。')
L(sc,'你收集了幾間房子的資訊，整理成一張表格。')
L(sc,'表格的每一列，代表一間房子。')
L(sc,'這一列，在機器學習裡叫做一筆「資料」，也叫「樣本」，英文是 instance。')
L(sc,'每一欄，是描述房子的一個特性：坪數、屋齡、離捷運站多遠。')
L(sc,'這些用來描述的欄位，叫做「特徵」，英文是 feature，講義裡也叫「屬性」。')
L(sc,'最後一欄是房價，也就是我們想預測的答案。')
L(sc,'這個答案，叫做「標籤」，英文是 label，也叫目標值 target。')
L(sc,'記住一句話：特徵是線索，標籤是答案。')
L(sc,'模型要學的，就是從線索推出答案的方法。')
sc='spam'
L(sc,'回到垃圾信的例子，也能做成一樣的表格。')
L(sc,'每一封信，就是一筆資料。')
L(sc,'特徵可以是：信裡出現幾次「免費」、有沒有可疑連結、認不認識寄件人。')
L(sc,'標籤，就是這封信是不是垃圾信。')
sc='clsreg'
L(sc,'你可能發現了，這兩個例子的答案，長得不太一樣。')
L(sc,'垃圾信的答案只有「是」或「不是」，是從幾個固定的類別裡選一個。')
L(sc,'這種任務，叫做「分類」，英文是 classification。')
L(sc,'房價的答案是一個數字，可能是 1,280 萬，也可能是 1,285 萬。','房價的答案是一個數字，可能是一千兩百八十萬，也可能是一千兩百八十五萬。')
L(sc,'這種預測一個連續數字的任務，叫做「回歸」，英文是 regression。')
L(sc,'分辨方法很簡單：答案是選一個類別，就是分類；答案是一個數字，就是回歸。')
L(sc,'來練習一下：明天會不會下雨？',gap=2.5)
L(sc,'是分類，因為答案只有「會」或「不會」。')
L(sc,'那明天最高氣溫幾度呢？',gap=2.5)
L(sc,'是回歸，因為答案是一個數字。')
L(sc,'這門課接下來的前半段，主要都在講分類。')
sc='types'
L(sc,'剛剛的例子有一個共同點：每一筆資料，都有標好的答案。')
L(sc,'就像寫練習題，每一題後面都附了解答，可以對答案、改錯。')
L(sc,'這種有標準答案可以學的方式，叫做「監督式學習」，英文是 supervised learning。')
L(sc,'分類和回歸，都屬於監督式學習。')
L(sc,'但如果資料沒有答案呢？')
L(sc,'例如一家飲料店有十萬筆消費紀錄，但沒有人告訴你，顧客該怎麼分類。')
L(sc,'電腦可以自己把相似的顧客放在一起：像是愛喝甜的學生族，和早上只買黑咖啡的上班族。')
L(sc,'這種沒有答案、讓電腦自己找出規律的方式，叫做「非監督式學習」。')
L(sc,'還有第三種，有點像訓練小狗：做對了給零食，做錯了就沒有。')
L(sc,'電腦不斷嘗試，從獎勵和懲罰裡學會怎麼做比較好，例如學下棋、玩遊戲。')
L(sc,'這叫做「強化學習」，英文是 reinforcement learning。')
L(sc,'講義裡還有半監督式和自監督式學習，我們下一集再慢慢講。')
sc='flow'
L(sc,'最後，我們把整個機器學習的流程，串成一條線。')
L(sc,'第一步，定義問題：我要預測什麼？是分類，還是回歸？')
L(sc,'第二步，收集資料。')
L(sc,'第三步，整理資料：補上缺漏、修正錯誤，把資料變成電腦看得懂的樣子。')
L(sc,'這一步叫做「資料前處理」，是第二單元的主題。')
L(sc,'第四步，把資料分成兩份：一份拿來學習，叫「訓練集」；一份留著考試，叫「測試集」。')
L(sc,'第五步，訓練模型：讓電腦從訓練集裡找出規則。')
L(sc,'第六步，評估：用模型沒看過的測試集來考它，看它準不準。')
L(sc,'最後，模型夠好的話，就拿去預測真正的新資料。')
sc='exam'
L(sc,'為什麼一定要分成訓練集和測試集？')
L(sc,'想像一下，如果期末考的題目，跟練習題一模一樣。')
L(sc,'就算考一百分，也不代表你真的學會了，可能只是把答案背起來。')
L(sc,'模型也是一樣，要用它沒看過的資料來考，才知道它是不是真的學會了。')
L(sc,'講義也特別強調：訓練集和測試集，必須彼此獨立。')
sc='example'
L(sc,'我們用一個小例子，把今天學的東西全部串起來。')
L(sc,'這裡有六封已經標好答案的信。')
L(sc,'特徵有兩個：「免費」出現幾次，以及有沒有連結。')
L(sc,'仔細看，三封垃圾信都有連結，而且「免費」至少出現兩次。')
L(sc,'正常信呢，要嘛沒有連結，要嘛「免費」最多只出現一次。')
L(sc,'於是電腦可以學到一條規則：先問有沒有連結，再問「免費」是不是出現兩次以上。')
L(sc,'兩個都是「是」，就判斷為垃圾信。這條規則，就是一個很簡單的模型。')
L(sc,'現在來了一封新信：「免費」出現三次，而且有連結。')
L(sc,'有連結，是；免費兩次以上，是。模型判斷：垃圾信。')
L(sc,'這種一層一層問問題來做判斷的模型，就是後面會學到的「決策樹」的雛形。')
