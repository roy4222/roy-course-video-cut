c=L('白話是：「它喊有的時候，可以信幾成？」垃圾郵件過濾最在乎它，因為把重要的信丟進垃圾桶，很麻煩。')
d=L('只看「模型說沒有」這一欄：說沒有的裡面，真的沒有的比例，叫「陰性預測值」，Negative Predictive Value，NPV，等於 TN 除以 TN 加 FN。')
