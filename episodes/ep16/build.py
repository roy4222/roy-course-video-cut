import random
random.seed(7)
def cloud(cx,cy,n):
    out=[]
    while len(out)<n:
        u=random.gauss(0,2.2);v=random.gauss(0,0.9)
        x=cx+u*0.707-v*0.707;y=cy+u*0.707+v*0.707
        if 1<x<19 and 1<y<19: out.append((round(x,2),round(y,2)))
    return out
